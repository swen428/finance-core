def parser_blocks(rows: list[dict[str, Any]]) -> tuple[parser.ParserOcrBlock, ...]:
    return tuple(
        parser.ParserOcrBlock(
            **{
                key: value
                for key, value in row.items()
                if key in parser.ParserOcrBlock.__dataclass_fields__
            }
        )
        for row in rows
    )


def counts(conn: sqlite3.Connection) -> tuple[int, ...]:
    return tuple(
        (
            conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]
            if conn.execute(
                "SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (table,)
            ).fetchone()
            else 0
        )
        for table in (
            "parser_outputs",
            "parser_proposal_field_evidence",
            "receipt_ocr_proposal_links",
            "transactions",
            "receipts",
            "receipt_items",
            "receipt_item_allocation_fact_sets",
            "parser_proposal_confirmations",
            "calculation_snapshots",
            "receipt_proposal_conversions",
            "parser_proposal_conversion_audit",
        )
    )


def call(conn: sqlite3.Connection, suffix: str, **identity: Any):
    return ingest(
        conn,
        extraction_public_id=f"rocr_{suffix}",
        proposal_public_id=f"prop_{suffix}",
        link_public_id=f"ropl_{suffix}",
        **identity,
    )


@pytest.mark.parametrize("vector", VECTORS, ids=lambda vector: vector["format"])
def test_actual_synthetic_vector_preserves_v1_and_recovers_only_v2(vector):
    name = "synthetic_mixed_receipt." + ("jpg" if vector["format"] == "jpeg" else "png")
    source = FIXTURES.parent / "linux_receipt_ocr" / name
    assert hashlib.sha256(source.read_bytes()).hexdigest() == vector["source_sha256"]
    blocks = parser_blocks(vector["blocks"])
    assert len(blocks) == 32
    old = parser.parse_receipt_total(blocks, extraction_status="succeeded")
    assert old.amount.value is None and old.amount.block_sequence_indexes == ()
    for ordered in (blocks, tuple(reversed(blocks))):
        result = parser.parse_receipt_total(
            ordered, extraction_status="succeeded", parser_version="v2"
        )
        assert result.amount.value == "12.34" and result.currency.value == "HKD"
        assert result.amount.block_sequence_indexes == (22, 23, 24, 25)
        assert result.amount.excerpt == "fit TOTAL HKD 12.34"
    # The v2 grouping supplies no new AI role-proof groups.
    assert frozenset({22, 23, 24, 25}) not in parser.proven_layout_line_indexes(blocks)


@pytest.mark.parametrize("case", LEGACY["cases"], ids=lambda case: case["suffix"])
@pytest.mark.parametrize("explicit_version", [False, True], ids=["default", "explicit-v1"])
def test_frozen_old_code_persisted_records_replay_exactly(
    migrated_temp_db_connection, tmp_path, case, explicit_version
):
    conn = migrated_temp_db_connection
    suffix = case["suffix"]
    attachment = legacy._persist_attachment(conn, tmp_path, suffix=suffix)
    engine = legacy.FakeEngine(
        result=ocr.ReceiptOcrEngineResult(
            ocr.ReceiptOcrExtractionStatus.SUCCEEDED,
            tuple(ocr.ReceiptOcrBlock(**row) for row in case["blocks"]),
            "ok",
        )
    )
    engine._identity = ocr.ReceiptOcrEngineIdentity(**case["engine_identity"])
    extraction = ocr.extract_and_persist_receipt_ocr_evidence(
        conn, public_id=f"rocr_{suffix}", attachment_id=attachment, engine=engine
    )
    assert extraction.extraction_fingerprint == case["extraction_fingerprint"]
    assert extraction.normalized_result_hash == case["normalized_result_hash"]
    for table, rows in case["stored"].items():
        for row in rows:
            columns = ", ".join(row)
            parameters = ", ".join("?" for _ in row)
            conn.execute(
                f"INSERT INTO {table} ({columns}) VALUES ({parameters})", tuple(row.values())
            )
    conn.execute(
        "UPDATE raw_intake_records SET parser_output_id = ?, status = ?",
        (case["result"]["parser_output_id"], "parsed_pending_confirmation"),
    )
    conn.commit()
    before = counts(conn)
    database_before = _source_state(conn)
    stored_before = {
        table: [dict(row) for row in conn.execute(f"SELECT * FROM {table} ORDER BY id")]
        for table in case["stored"]
    }
    identity = {"parser_contract_version": case["result"]["parser_contract_version"]}
    if explicit_version:
        identity["parser_version"] = "v1"
    result = call(conn, suffix, **identity)
    assert result.idempotent is True
    for name in (
        "extraction_public_id",
        "proposal_public_id",
        "parser_output_id",
        "link_public_id",
        "proposal_input_hash",
        "proposal_result_hash",
        "parser_contract_version",
        "parse_status",
    ):
        assert getattr(result, name) == case["result"][name]
    assert list(result.ambiguity_flags) == case["result"]["ambiguity_flags"]
    assert counts(conn) == before and _source_state(conn) == database_before
    for table, rows in stored_before.items():
        assert [dict(row) for row in conn.execute(f"SELECT * FROM {table} ORDER BY id")] == rows
    with pytest.raises(ProposalIdempotencyConflictError):
        call(conn, suffix, **V2)
    assert counts(conn) == before
    # Existing raw pointer also forbids new IDs and another-version proposal.
    with pytest.raises(
        (
            ProposalSourceBindingConflictError,
            ProposalIdempotencyConflictError,
            UnusableOcrEvidenceError,
        )
    ):
        ingest(
            conn,
            extraction_public_id=f"rocr_{suffix}",
            proposal_public_id=f"prop_new_{suffix}",
            link_public_id=f"ropl_new_{suffix}",
            **V2,
        )
    assert counts(conn) == before and all(value == 0 for value in before[3:])


