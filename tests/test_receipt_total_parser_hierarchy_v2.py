def _prepare_aggregate(conn, tmp_path):
    suffix = "aggregate"
    legacy._prepare_extraction(conn, tmp_path, suffix=suffix, blocks=legacy._sgd_blocks())
    other_attachment = legacy._persist_attachment(conn, tmp_path, suffix="aggregate_other")
